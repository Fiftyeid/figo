# ------------------------------------------------------------------ checks (vidIQ criteria)
def tag_chars(tags):
    """YouTube's 500-character tag budget: commas count, multi-word tags count with quotes."""
    return sum(len(t) + (2 if " " in t else 0) for t in tags) + len(tags) - 1


def check(item, desc_text):
    t = item["title"]
    k = item["keyword"]
    pos = t.find(k)
    norm = lambda s: s.replace("أ", "ا").replace("إ", "ا").replace("ى", "ي")
    first = desc_text.split("\n")[0]
    res = dict(
        title_len=len(t),
        kw_pos=pos,
        kw_in_title=0 <= pos and pos + len(k) <= 40,
        kw_in_desc=norm(k) in norm(first),
        kw_in_tags=norm(item["tags"][0]) == norm(k),
        n_tags=len(item["tags"]),
        tag_chars=tag_chars(item["tags"]),
        n_hashtags=item["hashtags"].count("#"),
    )
    res["ok"] = (res["kw_in_title"] and res["kw_in_desc"] and res["kw_in_tags"] and res["title_len"] <= 70
                 and 5 <= res["n_tags"] and res["tag_chars"] <= 500 and 2 <= res["n_hashtags"] <= 5)
    return res


def short_desc(sp):
    return "\n".join(sp["desc"] + [LINK_LINE, sp["hashtags"]])


def when(k):
    d = LONG_START + dt.timedelta(days=k)
    if k:
        d = d.replace(hour=SHORT_HOUR)
    h = d.hour - 12 if d.hour > 12 else d.hour
    return (f"{DAYS[d.weekday()]} {d.day} {MONTHS[d.month - 1]}".translate(AR),
            f"{h}:{d.minute:02d} م".translate(AR), d)


def secs(sid):
    import shorts
    P = shorts.make_plan(next(s for s in shorts.SHORTS if s["id"] == sid))
    return P["T_out"]


